"""Timeline chart of one replayed episode (the showcase poster)."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from telemetry import feature_names as fn  # noqa: E402

_PHASE_COLORS = {"normal": "#e8f5e9", "drift": "#fff8e1", "fault": "#ffebee"}
_PHASE_LABELS = {
    "normal": "normal",
    "drift": "harmless drift (traffic ramp)",
    "fault": "real fault",
}


def _spans(phase: np.ndarray):
    start = 0
    for t in range(1, len(phase) + 1):
        if t == len(phase) or phase[t] != phase[start]:
            yield str(phase[start]), start, t
            start = t


def plot_timeline(episode, run, out: str | Path, title: str | None = None) -> Path:
    """Metric, MMD² vs ε, shaded phases, alert marker and predicted type."""
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    from ewat.synthetic.generator import SERVICES

    minutes = np.arange(len(episode.phase)) * 0.5
    tgt = SERVICES.index(episode.target) if episode.target else 0
    feat = {
        "fail_slow_latency": fn.M_LATENCY_P99,
        "intermittent_error": fn.M_ERROR_RATE,
        "cpu_starvation": fn.M_CPU_UTIL,
        "resource_leak": fn.M_RAM_UTIL,
    }.get(episode.scenario, fn.M_LATENCY_P99)
    metric = episode.signal[:, tgt, feat]
    load = episode.signal[:, SERVICES.index("frontend"), fn.M_NET_SAT]
    mmd = run.array("mmd2")
    eps = run.steps[0].epsilon
    regime = run.array("regime")

    plt.rcParams.update({"font.size": 12, "font.family": "DejaVu Sans"})
    fig, (ax1, ax2) = plt.subplots(
        2, 1, figsize=(12.8, 7.2), dpi=100, sharex=True, gridspec_kw={"height_ratios": [1, 1.15]}
    )
    for ax in (ax1, ax2):
        for ph, a, b in _spans(episode.phase):
            ax.axvspan(minutes[a], minutes[b - 1] + 0.5, color=_PHASE_COLORS[ph], zorder=0)
        ax.grid(alpha=0.3)

    name = fn.FEATURE_NAMES[feat]
    ax1.plot(
        minutes, metric, color="#c62828", lw=2, label=f"{episode.target or SERVICES[0]} · {name}"
    )
    ax1.set_ylabel(name)
    ax1b = ax1.twinx()
    ax1b.plot(minutes, load, color="#1565c0", lw=1.5, alpha=0.7, label="frontend traffic (net_sat)")
    ax1b.set_ylabel("traffic")
    h1, l1 = ax1.get_legend_handles_labels()
    h2, l2 = ax1b.get_legend_handles_labels()
    ax1.legend(h1 + h2, l1 + l2, loc="upper left", fontsize=10, framealpha=0.9)
    gain = episode.params.get("load_gain")
    for ph, a, b in _spans(episode.phase):
        label = _PHASE_LABELS[ph] + (f" ×{gain:.1f}" if ph == "drift" and gain else "")
        ax1.text(
            (minutes[a] + minutes[b - 1]) / 2,
            1.02,
            transform=ax1.get_xaxis_transform(),
            ha="center",
            va="bottom",
            fontsize=12,
            fontweight="bold",
            s=label,
        )

    ax2.plot(minutes, mmd / eps, color="#4a148c", lw=2, label="drift score MMD² / ε (RFF)")
    ax2.axhline(1.0, color="black", ls="--", lw=1.5, label="alert threshold ε (q99.5 of normal)")
    absorbed = np.flatnonzero(regime == "absorbed")
    for k, t in enumerate(absorbed):
        ax2.axvline(
            minutes[t],
            color="#f9a825",
            lw=2,
            label="drift typed harmless → reference reset" if k == 0 else None,
        )
    alert = run.first_alert
    if alert is not None:
        ax2.axvline(minutes[alert.t], color="#c62828", lw=2.5, label="ALERT")
        ax2.annotate(
            f"ALERT  t+{(alert.t - (episode.fault_start or 0)) * 30:.0f} s after onset\n"
            f"type: {alert.alert_type}  (p={alert.probability:.2f})",
            xy=(minutes[alert.t], np.nanmax(mmd / eps) * 0.9),
            xytext=(-12, 0),
            textcoords="offset points",
            ha="right",
            va="top",
            fontsize=12,
            fontweight="bold",
            color="#c62828",
            bbox={"boxstyle": "round", "fc": "white", "ec": "#c62828"},
        )
    ax2.set_ylabel("MMD² / ε")
    ax2.set_xlabel("time (minutes, 30 s steps)")
    ax2.set_ylim(0, max(3.0, float(np.nanmax(mmd / eps)) * 1.08))
    ax2.legend(loc="upper left", fontsize=10, framealpha=0.9)
    fig.suptitle(
        title
        or f"EWAT · synthetic episode `{episode.scenario}` seed {episode.seed} — "
        "harmless drift is absorbed, the fault raises a typed alert",
        fontsize=13,
        fontweight="bold",
    )
    fig.text(
        0.995,
        0.005,
        "SYNTHETIC DATA · generated by ewat.synthetic · fixed seed",
        ha="right",
        fontsize=9,
        color="#555",
    )
    fig.tight_layout(rect=(0, 0.01, 1, 0.97))
    fig.savefig(out, dpi=100)
    plt.close(fig)
    return out
